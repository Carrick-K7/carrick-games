"""Regenerate the Villa's inline CC0 color maps from three local JPEGs. No network."""

import argparse
import base64
import hashlib
import io
import math
from pathlib import Path

from PIL import Image, ImageChops, ImageEnhance, ImageFilter, ImageStat


# Individual upstream downloads and author/scale notes are in README.md.
SOURCES = {
    'turf': ('suburban_soccer_park.jpg', (8192, 4096), 'ebf777257fd0225fe8d22bcb95a06e472a756cb9f7e33993f4467d037a2b4e2c'),
    'gravel': ('clean_pebbles_diff_1k.jpg', (1024, 1024), '902b115c4c0ace069862368b751e4799f338164cee62b53b61df3b6994165d95'),
    'timber': ('japanese_cedar_planks_diff_8k.jpg', (8192, 8192), '6bf1d467506e454d47e530b786ad2ca9d5e6bbbdb7cccac47b5f8d89a5413e6f'),
}
OUTPUT = Path(__file__).resolve().parents[1] / 'src/villaGroundScanData.ts'


def meadow_projection(pano, yaw_turns=0.74, forward=1.20):
    # Ground-plane inverse projection, not a rectangular cut from a spherical image.
    # The camera height (not surveyed) sets only the unit scale. Keep clear of the pole.
    width, height = pano.size
    n, overlap, ss = 512, 64, 2
    size = (n + overlap) * ss

    def uv(i, j):
        x = (i / (n * ss) - 0.5) * 1.25
        z = forward + (j / (n * ss) - 0.5) * 1.25
        return ((yaw_turns + math.atan2(x, z) / math.tau) * width,
                (0.5 + math.atan2(1.5, math.hypot(x, z)) / math.pi) * height)

    cells = []
    for y in range(0, size, 16):
        for x in range(0, size, 16):
            quad = (*uv(x, y), *uv(x, y+16), *uv(x+16, y+16), *uv(x+16, y))
            cells.append(((x, y, x+16, y+16), quad))
    sample = pano.transform((size, size), Image.Transform.MESH, cells, Image.Resampling.BICUBIC)
    sample = sample.resize((n + overlap, n + overlap), Image.Resampling.LANCZOS)
    # Both axes close with minimum-error cuts in overlapping real blade pixels.
    sample = close_x(sample, n).transpose(Image.Transpose.TRANSPOSE)
    return close_x(sample, n).transpose(Image.Transpose.TRANSPOSE)


def close_x(image, n):
    width, height = image.size
    b, mid = width - n, (width - n) // 2
    left, over = image.crop((0, 0, b, height)), image.crop((n, 0, width, height))
    cost = ImageChops.difference(left, over).convert('L').filter(ImageFilter.BoxBlur(1)).load()
    prev = [float('inf')] * b
    prev[mid] = 0
    paths = []
    for y in range(height):
        row, pred = [float('inf')] * b, bytearray(b)
        for x in range(4, b - 4):
            best = min(range(x-1, x+2), key=prev.__getitem__)
            row[x], pred[x] = prev[best] + cost[x, y], best
        prev = row
        paths.append(pred)
    # Pin the endpoints together so the second axis also wraps the first cut.
    mask, cut = bytearray(b * height), mid
    for y in reversed(range(height)):
        mask[y*b:y*b+cut] = b'\xff' * cut
        mask[y*b+cut] = 128
        cut = paths[y][cut]
    out = image.crop((0, 0, n, height))
    out.paste(over, (0, 0), Image.frombytes('L', (b, height), bytes(mask)))
    return out


def sawn_face(photo):
    # Only pixels inside ONE plank (native joints at about x=6480 and x=7056).
    # Stagger two copies of its grain instead of printing a joint or stretching
    # a single narrow board face across the entire width of authored stock.
    strip = photo.crop((6536, 0, 6976, 8192)).transpose(Image.Transpose.ROTATE_90)
    strip = close_x(strip.resize((1056, 152), Image.Resampling.LANCZOS), 1024)
    pieces = [strip, ImageChops.offset(strip, 419, 0)]
    out = Image.new('RGB', (1024, 256))
    for i, piece in enumerate(pieces):
        seam = piece.copy()
        seam.paste(pieces[i-1].crop((0, 128, 1024, 152)), (0, 128))
        segment = close_x(seam.transpose(Image.Transpose.TRANSPOSE), 128)
        out.paste(segment.transpose(Image.Transpose.TRANSPOSE), (0, 128*i))
    return out


def grade(image, saturation, contrast, mean):
    image = ImageEnhance.Color(image).enhance(saturation)
    channels = []
    for channel, center, target in zip(image.split(), ImageStat.Stat(image).mean, mean):
        lut = [max(0, min(255, round((i - center) * contrast + target))) for i in range(256)]
        channels.append(channel.point(lut))
    return Image.merge('RGB', channels)


def build(inputs):
    lines = ['// Generated by ../assets-sources/prepare_ground_scans.py. Poly Haven CC0; see its README.',
             'export const VILLA_GROUND_SCANS = {']
    for key, (filename, dimensions, digest) in SOURCES.items():
        data = (inputs / filename).read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError(f'{filename}: unexpected source SHA-256')
        with Image.open(io.BytesIO(data)) as im:
            if im.format != 'JPEG' or im.mode != 'RGB' or im.size != dimensions:
                raise ValueError(f'{filename}: unexpected source dimensions, format or channels')
            if key == 'turf':
                rgb = grade(meadow_projection(im), 0.85, 1.0, (80, 105, 65))
                quality = 82
            elif key == 'gravel':
                rgb = grade(im, 0.67, 1.12, (153, 147, 139))
                quality = 79
            else:
                rgb = grade(sawn_face(im), 0.46, 1.28, (133, 106, 83))
                quality = 83
        buf = io.BytesIO()
        rgb.save(buf, 'WEBP', quality=quality, method=6)
        webp = buf.getvalue()
        print(f'{key:6s} {rgb.size} {len(webp):7d} B  {hashlib.sha256(webp).hexdigest()}')
        lines.append(f"  {key}: 'data:image/webp;base64,{base64.b64encode(webp).decode('ascii')}',")
    return ('\n'.join([*lines, '} as const;', ''])).encode('ascii')


if __name__ == '__main__':
    args = argparse.ArgumentParser(description=__doc__)
    args.add_argument('inputs', type=Path, help='directory containing the three pinned source JPEGs')
    args.add_argument('--write', action='store_true', help='write the data-only module; default: compare')
    a = args.parse_args()
    payload = build(a.inputs)
    if a.write:
        OUTPUT.write_bytes(payload)
    elif not OUTPUT.is_file() or OUTPUT.read_bytes() != payload:
        raise SystemExit('Module differs (check source files and Pillow/libwebp versions).')
    print(f'{OUTPUT.name}: {len(payload)} B')
